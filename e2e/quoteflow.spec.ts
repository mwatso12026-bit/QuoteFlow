import { test, expect, type Page } from '@playwright/test'
async function navigate(page: Page, name: string) {
  const menu = page.getByRole('button', { name: 'Open navigation', exact: true })
  if (await menu.isVisible()) await menu.click()
  await page
    .getByRole('navigation', { name: 'Main navigation' })
    .getByRole('button', { name, exact: true })
    .click()
}
test('request to estimate to won persists after reload', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Lead pipeline' })).toBeVisible()
  await navigate(page, 'Request form')
  await page.getByLabel('Customer name').fill('Alex Demo')
  await page.getByLabel('Email address').fill('alex@example.com')
  await page.getByLabel('Service needed').fill('Fence repair')
  await page.getByLabel('Project details').fill('Repair gate and latch')
  await page.getByRole('button', { name: 'Submit request' }).click()
  await expect(page.getByRole('status')).toContainText('Request received')
  await navigate(page, 'Leads')
  await page.getByLabel('Search leads').fill('Alex Demo')
  await page.getByRole('button', { name: 'View Alex Demo' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Open estimate' }).click()
  await page.getByLabel('Item 1 description').fill('Repair gate')
  await page.getByLabel('Item 1 quantity').fill('2')
  await page.getByLabel('Item 1 price').fill('12.50')
  await page.getByRole('button', { name: 'Add line item' }).click()
  await page.getByLabel('Item 2 description').fill('Latch')
  await page.getByLabel('Item 2 price').fill('5')
  await expect(page.getByTestId('estimate-total')).toHaveText('$30')
  await page.getByRole('button', { name: 'Save estimate' }).click()
  await expect(page.getByRole('status')).toContainText('Estimate saved')
  await navigate(page, 'Leads')
  await page.getByRole('button', { name: 'View Alex Demo' }).click()
  await expect(page.getByLabel('Lead status')).toHaveValue('Quoted')
  await page.getByLabel('Lead status').selectOption('Won')
  await page.getByRole('button', { name: 'Save lead' }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'View Alex Demo' })).toContainText('Won')
  await expect(page.getByRole('button', { name: 'View Alex Demo' })).toContainText('$30')
  await page.getByRole('button', { name: 'View Alex Demo' }).click()
  await page.getByRole('button', { name: 'Open estimate' }).click()
  await page.getByLabel('Item 1 price').fill('15')
  await page.getByRole('button', { name: 'Save estimate' }).click()
  await navigate(page, 'Leads')
  await expect(page.getByRole('button', { name: 'View Alex Demo' })).toContainText('Won')
  await expect(page.getByRole('button', { name: 'View Alex Demo' })).toContainText('$35')
})
test('reset confirmation and keyboard dialog', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'View Marcus Reed' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(page.getByRole('button', { name: 'View Marcus Reed' })).toBeFocused()
  await page.getByRole('button', { name: 'Reset demo data' }).click()
  await page.getByRole('button', { name: 'Keep my changes' }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await page.getByRole('button', { name: 'Reset demo data' }).click()
  await page.getByRole('button', { name: 'Reset workspace' }).click()
  await expect(page.getByRole('status')).toContainText('Demo workspace reset')
})
for (const width of [375, 768, 1440]) {
  test('responsive layout at ' + width, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto('/')
    await expect(page.getByRole('heading', { name: 'Lead pipeline' })).toBeVisible()
    expect(
      await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth),
    ).toBe(true)
    await page.screenshot({ path: 'docs/screenshots/dashboard-' + width + '.png', fullPage: true })
    await navigate(page, 'Request form')
    await expect(page.getByLabel('Customer name')).toBeVisible()
    expect(
      await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth),
    ).toBe(true)
    await navigate(page, 'Estimates')
    await page.getByRole('button', { name: 'New estimate', exact: true }).click()
    await expect(page.getByLabel('Customer')).toBeVisible()
    expect(
      await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth),
    ).toBe(true)
  })
}
test('corrupt saved data is not overwritten', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('quoteflow:workspace:v1', 'broken'))
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('could not be read')
  await expect(page.getByRole('button', { name: 'View Olivia Bennett' })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('quoteflow:workspace:v1'))).toBe('broken')
})
test('mobile navigation traps focus and closes accessibly', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 900 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Lead pipeline' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Main navigation' })).toBeHidden()
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Tab')
  expect(await page.evaluate(() => !!document.activeElement?.closest('[role="dialog"]'))).toBe(true)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(page.getByRole('button', { name: 'Open navigation' })).toBeFocused()
})
